/**
 * 랜덤 포춘 메시지 가져오기
 * @param previousIndex 이전에 표시된 메시지 인덱스 (중복 방지)
 * @returns 랜덤 메시지와 인덱스
 */
export function getRandomFortune(previousIndex: number | null = null): { message: string; index: number } {
  let index: number;

  // 이전과 다른 메시지 선택 (중복 방지)
  do {
    index = Math.floor(Math.random() * FORTUNE_MESSAGES.length);
  } while (index === previousIndex && FORTUNE_MESSAGES.length > 1);

  return {
    message: FORTUNE_MESSAGES[index],
    index,
  };
}
